// LANGUAGE FUNCTION

function render(lang) {

const t = dict[lang] || dict.en;
const locale = {en:"en-IN", hi:"hi-IN", mr:"mr-IN"}[lang] || "en-IN";

document.documentElement.lang = lang;
document.title = t.pageTitle;

document.querySelectorAll("[data-t]").forEach(el => {

const k = el.dataset.t;

if (Object.hasOwn(t, k)) {
el.textContent = t[k];
}

});

document.querySelectorAll("[data-t-aria]").forEach(el => {
const k = el.dataset.tAria;
if (Object.hasOwn(t, k)) {
el.setAttribute("aria-label", t[k]);
}
});

document.querySelectorAll("[data-t-alt]").forEach(el => {
const k = el.dataset.tAlt;
if (Object.hasOwn(t, k)) {
el.setAttribute("alt", t[k]);
}
});

const weddingDate = new Date("2026-12-02T00:00:00+05:30");
const localizedDate = new Intl.DateTimeFormat(locale, {
day: "numeric",
month: "long",
year: "numeric"
}).format(weddingDate);

document.getElementById("footerDate").textContent = localizedDate;

document.getElementById("eventGrid").innerHTML =
t.eventData.map(e => `
<article class="event">
<div class="symbol">✧</div>
<h3>${e[0]}</h3>
<div class="date">${e[1]}</div>
${e[2] ? `<div class="time">${e[2]}</div>` : ""}
</article>
`).join("");

}


// LANGUAGE SELECTOR

document.getElementById("lang").addEventListener("change", e => {
render(e.target.value);
});

render("en");

// Keep the navigation highlight in sync with the section in view.
const sectionLinks = [...document.querySelectorAll('header nav a[href^="#"]')];
const sectionsById = new Map(
sectionLinks.map(link => [link.hash.slice(1), document.getElementById(link.hash.slice(1))])
);

function setCurrentSection(sectionId) {
sectionLinks.forEach(link => {
if (link.hash === `#${sectionId}`) {
link.setAttribute("aria-current", "location");
} else {
link.removeAttribute("aria-current");
}
});
}

setCurrentSection("home");

const sectionObserver = new IntersectionObserver(entries => {
const visibleSection = entries
.filter(entry => entry.isIntersecting)
.sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];

if (visibleSection) {
setCurrentSection(visibleSection.target.id);
}
}, {
rootMargin: "-30% 0px -55% 0px",
threshold: [0, 0.25, 0.5, 0.75, 1]
});

sectionsById.forEach(section => {
if (section) {
sectionObserver.observe(section);
}
});

// COUNTDOWN TIMER

const target = new Date("2026-12-02T00:00:00+05:30").getTime();

function updateTimer() {

let n = Math.max(0, target - Date.now());

let v = {

days: Math.floor(n / 86400000),

hours: Math.floor(n % 86400000 / 3600000),

minutes: Math.floor(n % 3600000 / 60000),

seconds: Math.floor(n % 60000 / 1000)

};

Object.entries(v).forEach(([k, x]) => {

const value = String(x).padStart(2, "0");
const homeKey = `home${k[0].toUpperCase()}${k.slice(1)}`;

document.getElementById(homeKey).textContent = value;

});

}

updateTimer();

setInterval(updateTimer, 1000);


